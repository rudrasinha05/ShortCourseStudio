async function attempt(claims={},withCookie=true){
 const start=await get("/admin/auth/google/start");const provider=new URL(loc(start));
 assert.equal(provider.origin,"https://accounts.google.com");
 assert.equal(provider.searchParams.get("redirect_uri"),origin+"/admin/auth/google/callback");
 assert.equal(provider.searchParams.get("code_challenge_method"),"S256");
 assert.equal(provider.searchParams.get("prompt"),"select_account");
 const state=provider.searchParams.get("state"),url="/admin/auth/google/callback?code=synthetic-auth-code&state="+state;
 const stateCookie=cookie(start,"__Host-scs-admin-google");
 assert.ok(stateCookie);
 if(!withCookie)return [await get(url),url,stateCookie];
 const now=Math.floor(Date.now()/1000);
 const payload=base64({iss:"https://accounts.google.com",aud:client,sub:"google-owner-id",hd:"example.invalid",email:ownerEmail,email_verified:true,exp:now+600,iat:now,nonce:provider.searchParams.get("nonce"),...claims});
 const input=base64({alg:"RS256",kid:"mock-key"})+"."+payload;
 const signed=input+"."+sign("RSA-SHA256",Buffer.from(input),privateKey).toString("base64url");
 fetchMock.get("https://oauth2.googleapis.com").intercept({path:"/token",method:"POST"}).reply(200,{id_token:signed},mockHeaders);
 fetchMock.get("https://www.googleapis.com").intercept({path:"/oauth2/v3/certs",method:"GET"}).reply(200,{keys:[googleKey]},mockHeaders);
 return [await get(url,stateCookie),url,stateCookie];
}

